"""EON workspaces: isolated OpenJarvis instances.

Each workspace gets its own OPENJARVIS_HOME (config, persona, memory, task
databases), its own port, and its own allow-list of provider keys. The server
process is started with a minimal environment built from scratch, so a key that
is not on the workspace's allow-list never reaches that process.

Usage:  python -m eon.workspaces setup | status | start <workspace>
"""

from __future__ import annotations

import os
import stat
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Mapping, Optional, Tuple

PROVIDER_KEYS: Dict[str, str] = {"gemini": "GEMINI_API_KEY", "groq": "GROQ_API_KEY"}

# Variables a server process may inherit. Everything else is dropped.
_PASSTHROUGH = ("PATH", "HOME", "LANG", "LC_ALL", "TERM", "TMPDIR",
                "SSL_CERT_FILE", "REQUESTS_CA_BUNDLE", "VIRTUAL_ENV")


@dataclass(frozen=True)
class Workspace:
    name: str
    port: int
    providers: Tuple[str, ...]
    engine: str
    model: str
    chain: str
    profile: str
    identity: str
    addendum: str


_BASE_IDENTITY = (
    "You are EON, the AI operating partner of MD Studios and personal executive "
    "assistant to its owner. You run on the open-source OpenJarvis framework, but "
    "you are not called OpenJarvis, and you are not ChatGPT, Gemini or any other "
    "branded assistant. If asked who you are, say you are EON. "
)

WORKSPACES: Dict[str, Workspace] = {
    "personal": Workspace(
        name="personal",
        port=8001,
        providers=("gemini", "groq"),
        engine="cloud",
        model="gemini-3.6-flash",
        chain="cloud:gemini-3.6-flash,groq:openai/gpt-oss-120b",
        profile="personal",
        identity=_BASE_IDENTITY + "This is the Personal workspace. Your detailed behaviour rules follow.",
        addendum=(
            "\n## Workspace: Personal\n"
            "Tasks, reminders, schedule, personal research and decisions. "
            "Do not use or mention MD Studios client or business data here.\n"
        ),
    ),
    "md-studios": Workspace(
        name="md-studios",
        port=8002,
        # Only providers that state they do not train on API data.
        providers=("groq",),
        engine="groq",
        model="openai/gpt-oss-120b",
        chain="groq:openai/gpt-oss-120b",
        profile="shared",
        identity=_BASE_IDENTITY + "This is the MD Studios workspace. Your detailed behaviour rules follow.",
        addendum=(
            "\n## Workspace: MD Studios\n"
            "Business development, lead discovery and qualification, market research, "
            "proposals, clients and projects. Client and prospect information stays in "
            "this workspace. Do not use or mention personal matters here.\n"
        ),
    ),
}


def root() -> Path:
    return Path(os.environ.get("EON_ROOT") or (Path.home() / ".eon"))


def home(ws: Workspace) -> Path:
    return root() / ws.name


def core_persona() -> str:
    return (Path(__file__).parent / "persona" / "core.md").read_text(encoding="utf-8")


def render_config(ws: Workspace) -> str:
    return (
        "# Generated by eon.workspaces. Edit USER.md, MEMORY.md and keys.env instead.\n"
        "[engine]\n"
        f'default = "{ws.engine}"\n\n'
        "[intelligence]\n"
        f'default_model = "{ws.model}"\n\n'
        "[agent]\n"
        'default_agent = "simple"\n'
        f"default_system_prompt = '''{ws.identity}'''\n\n"
        "[tools]\n"
        'enabled = ["web_search"]\n\n'
        "[security]\n"
        f'profile = "{ws.profile}"\n\n'
        "[analytics]\n"
        "enabled = false\n"
        "choice_recorded = true\n"
    )


def keys_template(ws: Workspace) -> str:
    lines = [f"# Provider keys for the {ws.name} workspace. Only these names are honoured.",
             "# Type the key after the = sign. Never paste this file anywhere."]
    for p in ws.providers:
        lines.append(f'{PROVIDER_KEYS[p]}=""')
    return "\n".join(lines) + "\n"


def setup(ws: Workspace) -> Path:
    h = home(ws)
    h.mkdir(parents=True, exist_ok=True)
    (h / "config.toml").write_text(render_config(ws), encoding="utf-8")
    (h / "SOUL.md").write_text(core_persona() + ws.addendum, encoding="utf-8")
    for name, body in (("USER.md", "# User Profile\n\n"), ("MEMORY.md", "# Agent Memory\n\n")):
        if not (h / name).exists():
            (h / name).write_text(body, encoding="utf-8")
    keys = h / "keys.env"
    if not keys.exists():
        keys.write_text(keys_template(ws), encoding="utf-8")
    keys.chmod(stat.S_IRUSR | stat.S_IWUSR)
    return h


def _parse_env_file(path: Path) -> Dict[str, str]:
    out: Dict[str, str] = {}
    if not path.exists():
        return out
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        if line.startswith("export "):
            line = line[len("export "):]
        name, _, value = line.partition("=")
        out[name.strip()] = value.strip().strip('"').strip("'")
    return out


def load_keys(ws: Workspace) -> Dict[str, str]:
    """Return only the allow-listed, non-empty provider keys for ``ws``."""
    allowed = {PROVIDER_KEYS[p] for p in ws.providers}
    found = _parse_env_file(home(ws) / "keys.env")
    return {k: v for k, v in found.items() if k in allowed and v}


def build_env(ws: Workspace, parent: Optional[Mapping[str, str]] = None) -> Dict[str, str]:
    parent = os.environ if parent is None else parent
    env = {k: parent[k] for k in _PASSTHROUGH if k in parent}
    env.update(load_keys(ws))
    env["OPENJARVIS_HOME"] = str(home(ws))
    env["EON_WORKSPACE"] = ws.name
    env["EON_FAILOVER_CHAIN"] = ws.chain
    return env


def serve_argv(ws: Workspace) -> List[str]:
    return [sys.executable, "-m", "eon", "serve", "--host", "127.0.0.1",
            "--port", str(ws.port), "-e", ws.engine, "-m", ws.model, "-a", "simple"]


def status(ws: Workspace) -> str:
    keys = sorted(load_keys(ws))
    return (f"{ws.name:<11} port {ws.port}  engine {ws.engine:<6} model {ws.model}\n"
            f"            home {home(ws)}\n"
            f"            keys present: {', '.join(keys) if keys else 'NONE (edit keys.env)'}")


def main(argv: Optional[List[str]] = None) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    cmd = args[0] if args else "status"
    if cmd == "setup":
        for ws in WORKSPACES.values():
            print(f"set up {ws.name}: {setup(ws)}")
        return 0
    if cmd == "status":
        print("\n".join(status(ws) for ws in WORKSPACES.values()))
        return 0
    if cmd == "start":
        name = args[1] if len(args) > 1 else ""
        ws = WORKSPACES.get(name)
        if ws is None:
            print(f"usage: python -m eon.workspaces start {{{'|'.join(WORKSPACES)}}}")
            return 2
        if not load_keys(ws):
            print(f"No provider key for {ws.name}. Edit {home(ws) / 'keys.env'} first.")
            return 1
        argv_ = serve_argv(ws)
        os.execve(argv_[0], argv_, build_env(ws))
    print("usage: python -m eon.workspaces setup | status | start <workspace>")
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
